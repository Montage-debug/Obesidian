  const cached=old.split('<main class="sheet" contenteditable="true" spellcheck="false">')[1].split('</main>')[0].replace('简历内容基于本人提供的工程材料整理。','缓存保留验证');
  await page.evaluate(html=>localStorage.setItem('resume-gu-xingyu-editable-v5',html),cached);
  await page.reload();
  assert.equal(await page.locator('[data-academic-score]').count(),1);
  assert((await page.locator('footer').innerText()).includes('缓存保留验证'));
  assert(!(await page.locator('.sheet').innerText()).includes('GPA：xxx'));
  assert.equal(errors.length,0,errors.join('\n'));
  fs.writeFileSync(path.join(__dirname,'browser-check.json'),JSON.stringify({geometry,originalGeometry,errors,checks:['photo loaded','2 editable pages','browser persistence','HTML download contains edits and photo','download uses new storage key','original undergraduate GPA placement','cached draft migration retains unrelated edits','no browser script errors']},null,2));
  console.log('PASS: browser editing, save/download, cache migration, original print bounds');
  await browser.close();
