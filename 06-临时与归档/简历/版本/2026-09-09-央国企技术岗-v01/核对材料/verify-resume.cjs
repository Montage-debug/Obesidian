  // Verify the existing HTML, then a previously cached draft with independent edits.
  await page.goto(pathToFileURL(original).href);await page.emulateMedia({media:'print'});
  assert.equal(await page.locator('[data-academic-score]').count(),1);
  assert(!(await page.locator('.edu').first().innerText()).includes('2.55'));
  const originalGeometry=await page.locator('.sheet').evaluate(e=>({height:e.getBoundingClientRect().height,scroll:e.scrollHeight,footer:e.querySelector('footer').getBoundingClientRect().bottom-e.getBoundingClientRect().top}));
  console.log('Original geometry',JSON.stringify(originalGeometry));
  assert(originalGeometry.footer<originalGeometry.height-15,'Original would clip at print time');
